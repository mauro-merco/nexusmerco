// Requires jsdom on NODE_PATH; no application dependency is needed.
require('./test-description.cjs');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html>');
for (const key of ['document', 'Node', 'NodeFilter', 'HTMLElement']) global[key] = dom.window[key];
const { formatDescriptionRange, descriptionMark } = require('../src/lib/description-format.ts');
const { descriptionMarkdown } = require('../src/components/task-fields.tsx');
const editor = document.createElement('div');
document.body.append(editor);
function apply(html, startSelector, start, endSelector, end, color = 'blue') {
  editor.innerHTML = html;
  const range = document.createRange();
  range.setStart(editor.querySelector(startSelector).firstChild, start);
  range.setEnd(editor.querySelector(endSelector).firstChild, end);
  return formatDescriptionRange(editor, range, 'frame', color);
}
let result = apply('<p>before selected after</p>', 'p', 7, 'p', 15);
assert.equal(result.toString(), 'selected');
assert.equal(editor.querySelector('[data-description-kind]').textContent, 'selected');
assert.equal(descriptionMarkdown(editor.firstChild).trim(), `before ${descriptionMark('frame', 'blue', 'selected')} after`);
result = apply('<p>before <b>bold words</b> after</p><p>second paragraph</p>', 'b', 5, 'p + p', 6);
assert.equal(result.toString(), 'words aftersecond');
assert.equal(editor.querySelectorAll('[data-description-kind]').length, 1);
assert.equal(editor.querySelector('[data-description-block]').textContent, 'words aftersecond');
assert.equal(editor.firstChild.textContent, 'before bold ');
assert.equal(editor.lastChild.textContent, ' paragraph');
assert.equal(editor.querySelector('p div'), null);
const { renderToStaticMarkup } = require('react-dom/server');
const React = require('react');
const { MarkdownBody } = require('../src/lib/markdown.tsx');
const stored = [...editor.childNodes].map(descriptionMarkdown).join('');
assert.equal((stored.match(/\{\{d2:/g) || []).length, 1);
editor.innerHTML = renderToStaticMarkup(React.createElement(MarkdownBody, { text: stored, editable: true }));
assert.equal(editor.querySelectorAll('[data-description-block]').length, 1);
assert.equal(editor.querySelector('p div'), null);
assert.equal([...editor.childNodes].map(descriptionMarkdown).join(''), stored);
result = apply('<p>one two</p><p>three four</p><p>five six</p>', 'p', 4, 'p:last-child', 4);
assert.equal(editor.querySelectorAll('[data-description-kind]').length, 1);
assert.equal(editor.firstChild.textContent, 'one ');
assert.equal(editor.lastChild.textContent, ' six');
result = apply('<p><span data-description-kind="highlight" data-description-color="yellow">before selected after</span></p>', 'span', 7, 'span', 15);
assert.equal(editor.querySelector('[data-description-color="blue"]').textContent, 'selected');
assert.deepEqual([...editor.querySelectorAll('[data-description-color="yellow"]')].map(x => x.textContent), ['before ', ' after']);
formatDescriptionRange(editor, result, 'frame', null);
assert.equal(editor.querySelector('[data-description-color="blue"]'), null);
assert.equal(editor.textContent, 'before selected after');
result = apply('<p><span data-description-kind="highlight" data-description-color="yellow"><b>before selected after</b></span></p>', 'b', 7, 'b', 15, null);
assert.equal(result.toString(), 'selected');
assert.equal([...editor.querySelectorAll('b')].map(x => x.textContent).join(''), 'before selected after');
assert.equal([...editor.querySelectorAll('[data-description-kind]')].map(x => x.textContent).join(''), 'before  after');
const collapsed = document.createRange();
collapsed.selectNodeContents(editor); collapsed.collapse(true);
assert.equal(formatDescriptionRange(editor, collapsed, 'frame', 'blue'), null);
const outside = document.createRange(); outside.selectNodeContents(document.body);
assert.equal(formatDescriptionRange(editor, outside, 'frame', 'blue'), null);
console.log('Range regressions passed: partial text, cross-block selection, inline semantics, recolor, clear, collapsed and outside ranges.');
